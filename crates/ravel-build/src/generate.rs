//! Generated workspace manifests and host source.
//!
//! Mods inherit only the SDK and author serialization dependencies. JNI, core,
//! and runtime are direct host dependencies, never workspace exports.

use std::fmt::Write as _;
use std::path::Path;

use crate::{ENTRY_FUNCTION, PlannedMember};
use ravel_core::paths::{HOST_DIRECTORY, HOST_LIBRARY, PACKAGES_DIRECTORY};

pub(super) fn workspace_manifest(
    members: &[PlannedMember],
    ravel_root: &Path,
    author_dependencies: &toml::Table,
) -> String {
    let mut listed = vec![toml::Value::String(HOST_DIRECTORY.to_owned())];
    listed.extend(
        members
            .iter()
            .map(|member| format!("{PACKAGES_DIRECTORY}/{}", member.directory).into()),
    );
    let mut dependencies = author_dependencies.clone();
    dependencies.insert(
        "ravel-sdk".to_owned(),
        path_dependency(&ravel_root.join("crates/ravel-sdk")),
    );
    serialize(&table([(
        "workspace",
        table([
            ("resolver", "3".into()),
            ("members", toml::Value::Array(listed)),
            (
                "package",
                table([
                    ("edition", "2024".into()),
                    ("license", "MIT OR Apache-2.0".into()),
                    ("publish", false.into()),
                    ("rust-version", "1.95".into()),
                ]),
            ),
            ("dependencies", toml::Value::Table(dependencies)),
            (
                "lints",
                table([("rust", table([("unsafe_code", "forbid".into())]))]),
            ),
        ]),
    )]))
}

pub(super) fn host_manifest(
    members: &[PlannedMember],
    ravel_root: &Path,
    jni_dependency: &toml::Table,
) -> String {
    let mut dependencies = jni_dependency.clone();
    for name in ["ravel-core", "ravel-host-runtime"] {
        dependencies.insert(
            name.to_owned(),
            path_dependency(&ravel_root.join("crates").join(name)),
        );
    }
    for member in members {
        dependencies.insert(
            member.crate_name.clone(),
            path_dependency(
                &Path::new("..")
                    .join(PACKAGES_DIRECTORY)
                    .join(&member.directory),
            ),
        );
    }
    serialize(&table([
        (
            "package",
            table([
                ("name", "ravel-generated-host".into()),
                ("version", "0.0.0".into()),
                ("edition", table([("workspace", true.into())])),
                ("license", table([("workspace", true.into())])),
                ("publish", table([("workspace", true.into())])),
                ("rust-version", table([("workspace", true.into())])),
            ]),
        ),
        (
            "lib",
            table([
                ("name", HOST_LIBRARY.into()),
                (
                    "crate-type",
                    toml::Value::Array(vec!["cdylib".into(), "rlib".into()]),
                ),
            ]),
        ),
        ("dependencies", toml::Value::Table(dependencies)),
        ("lints", table([("workspace", true.into())])),
    ]))
}

fn path_dependency(path: &Path) -> toml::Value {
    table([("path", path.to_string_lossy().into_owned().into())])
}

fn table<const N: usize>(entries: [(&str, toml::Value); N]) -> toml::Value {
    toml::Value::Table(
        entries
            .into_iter()
            .map(|(key, value)| (key.to_owned(), value))
            .collect(),
    )
}

fn serialize(manifest: &toml::Value) -> String {
    format!(
        "# Generated by ravel-build. Every edit here is overwritten.\n{}",
        toml::to_string(manifest).expect("TOML values serialize")
    )
}

pub(super) fn host_source(members: &[PlannedMember]) -> String {
    let mut manifests = String::new();
    let mut pushes = String::new();
    for member in members {
        let constant = member.mod_id.as_str().to_uppercase();
        write!(
            manifests,
            "/// The manifest `{mod_id}` ships, read from the package itself.\n\
             const {constant}: &str = include_str!({path:?});\n\n",
            mod_id = member.mod_id,
            path = format!(
                "../../{PACKAGES_DIRECTORY}/{}/package.json",
                member.directory
            ),
        )
        .expect("a string accepts writes");
        write!(
            pushes,
            "        Member {{\n\
             \x20           package: {constant}.to_owned(),\n\
             \x20           value: {ident}::{ENTRY_FUNCTION}(side),\n\
             \x20       }},\n",
            ident = crate_ident(&member.crate_name),
        )
        .expect("a string accepts writes");
    }
    format!(
        "#![forbid(unsafe_code)]\n\
         \n\
         //! A host generated by `ravel-build` from the packages this instance holds.\n\
         //!\n\
         //! Every edit here is overwritten. What decides the contents is the set of\n\
         //! installed packages, and the way to change it is to install or remove one.\n\
         //!\n\
         //! This file is a member list and a JNI symbol. Resolution, admission and the\n\
         //! lifecycle all belong to `ravel-host-runtime`, which the statically composed\n\
         //! host calls too, so neither host can answer differently from the other.\n\
         \n\
         use jni::EnvUnowned;\n\
         use jni::objects::JClass;\n\
         use ravel_core::Side;\n\
         use ravel_host_runtime::Member;\n\
         \n\
         {manifests}\
         /// The packages this host was generated from.\n\
         ///\n\
         /// Public because the cdylib is not the only thing that has to be able to\n\
         /// name this set: the JVM enters the symbol below, and a test or a\n\
         /// diagnostic that drives the same members without a JVM needs the list\n\
         /// itself.\n\
         pub fn members(side: Side) -> Vec<Member> {{\n\
         \x20   vec![\n\
         {pushes}\
         \x20   ]\n\
         }}\n\
         \n\
         {entry_points}",
        entry_points = entry_points(),
    )
}

fn entry_points() -> &'static str {
    "/// Starts the installed mod set before game methods run.\n\
     #[jni::jni_mangle(\"dev.ravel.jvm.Hook\", \"ravelInitialize\")]\n\
     pub fn ravel_initialize<'local>(\n\
     \x20   env: EnvUnowned<'local>,\n\
     \x20   _class: JClass<'local>,\n\
     \x20   side: jni::sys::jint,\n\
     \x20   profiling_requested: jni::sys::jboolean,\n\
     ) {\n\
     \x20   ravel_host_runtime::enter(env, side, profiling_requested, members);\n\
     }\n\
     \n\
     /// Starts the integrated server's independent side-specific mod set.\n\
     #[jni::jni_mangle(\"dev.ravel.jvm.Hook\", \"ravelInitializeIntegratedServer\")]\n\
     pub fn ravel_initialize_integrated_server<'local>(\n\
     \x20   env: EnvUnowned<'local>,\n\
     \x20   _class: JClass<'local>,\n\
     ) {\n\
     \x20   ravel_host_runtime::enter_integrated(env, members);\n\
     }\n"
}

pub(super) fn crate_ident(crate_name: &str) -> String {
    crate_name.replace('-', "_")
}
