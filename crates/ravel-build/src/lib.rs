    const RECORD: &[u8] = br#"{"origin":"example"}"#;

    /// The game a fixture declares.
    ///
    /// Read from the running environment rather than written here, for two
    /// reasons: a crate under `crates/` may not name a Minecraft version, and a
    /// fixture that named one this build is not would be refused by `admitted`
    /// the moment the generated host was actually driven — which is how this
    /// was found.
    fn game() -> String {
        ravel_host_runtime::environment().minecraft
    }

    static NEXT: AtomicU32 = AtomicU32::new(0);

    /// One fixture's source, with the identity its manifest will declare.
    fn source(template: &str, id: &str) -> String {
        template.replace("{id}", id)
    }

    /// The digest a package's manifest declares for its source.
    ///
    /// Computed rather than recorded, because what is under test here is the
    /// build step and not the hashing: discovery owns that rule and its own
    /// suite checks it against digests taken from `sha256sum`. This only has to
    /// satisfy discovery so that a fixture reaches the code being tested.
    fn digest_of(bytes: &[u8]) -> String {
        let mut hasher = Sha256::new();
        hasher.update(bytes);
        let mut digest = [0_u8; 32];
        digest.copy_from_slice(&hasher.finalize());
        Sha256Digest::from_bytes(digest).to_string()
    }

    fn instance(label: &str) -> PathBuf {
        let unique = NEXT.fetch_add(1, Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!(
            "ravel-build-{label}-{}-{unique}",
            std::process::id()
        ));
        if root.exists() {
            fs::remove_dir_all(&root).expect("a stale instance is removable");
        }
        fs::create_dir_all(root.join(PACKAGES_DIRECTORY)).expect("an instance is creatable");
        root
    }

    /// This repository, standing in for the installation a player's Ravel is.
    fn ravel_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(Path::parent)
            .expect("the crate sits two levels under the repository")
            .to_owned()
    }

    /// Installs a package naming the one dependency every mod names.
    fn install(instance: &Path, directory: &str, id: &str, crate_name: &str, template: &str) {
        install_with(
            instance,
            directory,
            id,
            crate_name,
            template,
            "ravel-sdk.workspace = true\n",
        );
    }

    /// Installs a package the way a player would: a source tree with a manifest.
    ///
    /// `dependencies` is the body of the package's own `[dependencies]` table,
    /// written the way an author writes it against this repository, so a fixture
    /// can name the same inherited dependencies a mod under `test-mods/` does.
    fn install_with(
        instance: &Path,
        directory: &str,
        id: &str,
        crate_name: &str,
        template: &str,
        dependencies: &str,
    ) {
        let root = instance.join(PACKAGES_DIRECTORY).join(directory);
        fs::create_dir_all(root.join("src")).expect("a package directory is creatable");
        let source = source(template, id);
        let digest = digest_of(source.as_bytes());
        let record = digest_of(RECORD);
        fs::write(
            root.join(MANIFEST_FILE),
            format!(
                r#"{{
                  "schemaVersion": 1,
                  "id": "{id}",
                  "version": "1.0.0",
                  "compatibility": {{ "ravel": ">=0.0.0", "minecraft": ["{game}"] }},
                  "sides": ["client"],
                  "authors": [{{ "name": "Ravel" }}],
                  "license": "MIT",
                  "source": {{
                    "repository": "https://example.invalid/{id}",
                    "files": [{{ "path": "src/lib.rs", "sha256": "{digest}" }}]
                  }},
                  "provenance": {{ "record": "provenance.json", "sha256": "{record}" }}
                }}"#,
                game = game()
            ),
        )
        .expect("manifest written");
        fs::write(root.join("src/lib.rs"), &source).expect("source written");
        fs::write(root.join("provenance.json"), RECORD).expect("record written");
        // The manifest an author writes for a mod they develop against this
        // repository, unchanged. Nothing rewrites it on the way in.
        fs::write(
            root.join("Cargo.toml"),
            format!(
                "[package]\n\
                 name = \"{crate_name}\"\n\
                 version = \"1.0.0\"\n\
                 edition.workspace = true\n\
                 license.workspace = true\n\
                 publish.workspace = true\n\
                 rust-version.workspace = true\n\
                 \n\
                 [dependencies]\n\
                 {dependencies}\n\
                 [lints]\n\
                 workspace = true\n"
            ),
        )
        .expect("cargo manifest written");
    }

