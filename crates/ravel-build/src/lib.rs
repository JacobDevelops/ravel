/// The directory inside an instance the generated workspace is written to.
///
/// The parent of [`ravel_loader::PACKAGES_DIRECTORY`], so the workspace root is
/// above both the host and the installed packages. Cargo finds a member's
/// workspace root by walking up from the member, which is the whole reason the
/// root cannot live beside the host instead.
pub const WORKSPACE_DIRECTORY: &str = "ravel";

/// The library name the generated host produces, and the JVM loads.
pub const HOST_LIBRARY: &str = "ravel_bootstrap";

/// The entry function `ravel_sdk::export_mod!` writes into a package.
pub const ENTRY_FUNCTION: &str = "__ravel_entry";

/// What a host will be generated from, and the bytes that generate it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HostPlan {
    files: BTreeMap<String, String>,
    members: Vec<PlannedMember>,
    fingerprint: String,
}

impl HostPlan {
    /// Returns every generated file, keyed by its path under the instance's
    /// `ravel` directory, in path order.
    #[must_use]
    pub const fn files(&self) -> &BTreeMap<String, String> {
        &self.files
    }

    /// Returns the packages this host will be built from, in mod-id order.
    #[must_use]
    pub fn members(&self) -> &[PlannedMember] {
        &self.members
    }

    /// Returns the digest of the generated bytes.
    ///
    /// Two plans with one fingerprint generate one host. It is evidence about
    /// determinism rather than a cache key: what decides whether Cargo rebuilds
    /// is Cargo's own key over crate source, features, profile and toolchain.
    #[must_use]
    pub fn fingerprint(&self) -> &str {
        &self.fingerprint
    }
}

/// One installed package as the generated host will name it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PlannedMember {
    /// The identity its manifest declares.
    pub mod_id: String,
    /// The directory it is installed under.
    pub directory: String,
    /// The Cargo package name its own `Cargo.toml` declares.
    pub crate_name: String,
}

/// Plans a host for the packages an instance holds.
///
/// `ravel_root` is where this Ravel installation keeps its own crates, because
/// the generated workspace depends on them by path. Nothing here decides where
/// that is: `docs/decisions/shared-toolchain-and-build-cache.md` leaves the
/// installation layout to whatever owns it.
///
/// # Errors
///
/// Returns [`BuildRefused::MissingCargoManifest`] when an installed package
/// carries no `Cargo.toml`, [`BuildRefused::CargoManifest`] when that document
/// is not readable TOML or declares no package name, and
/// [`BuildRefused::DuplicateCrate`] when two packages declare one crate name —
/// which Cargo would refuse later and less clearly.
pub fn plan(discovered: &Discovered, ravel_root: &Path) -> Result<HostPlan, BuildRefused> {
    let mut members = Vec::with_capacity(discovered.packages().len());
    for package in discovered.packages() {
        let directory = package.directory().to_owned();
        let crate_name = crate_name(package.root(), &directory)?;
        if let Some(clash) = members
            .iter()
            .find(|planned: &&PlannedMember| planned.crate_name == crate_name)
        {
            return Err(BuildRefused::DuplicateCrate {
                crate_name,
                directory,
                first: clash.directory.clone(),
            });
        }
        members.push(PlannedMember {
            mod_id: package.manifest().id.as_str().to_owned(),
            directory,
            crate_name,
        });
    }

    let mut files = BTreeMap::new();
    files.insert(
        "Cargo.toml".to_owned(),
        workspace_manifest(&members, ravel_root),
    );
    files.insert("host/Cargo.toml".to_owned(), host_manifest(&members));
    files.insert("host/src/lib.rs".to_owned(), host_source(&members));

    let mut digest = Sha256::new();
    for (path, contents) in &files {
        digest.update(path.as_bytes());
        digest.update([0]);
        digest.update(contents.as_bytes());
        digest.update([0]);
    }
    let mut bytes = [0_u8; 32];
    bytes.copy_from_slice(&digest.finalize());
    let fingerprint = Sha256Digest::from_bytes(bytes).to_string();

    Ok(HostPlan {
        files,
        members,
        fingerprint,
    })
}

/// Reads the Cargo package name an installed package declares for itself.
fn crate_name(root: &Path, directory: &str) -> Result<String, BuildRefused> {
    let path = root.join("Cargo.toml");
    let document = match fs::read_to_string(&path) {
        Ok(document) => document,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Err(BuildRefused::MissingCargoManifest {
                directory: directory.to_owned(),
            });
        }
        Err(error) => {
            return Err(BuildRefused::CargoManifest {
                directory: directory.to_owned(),
                detail: error.to_string(),
            });
        }
    };
    let parsed: toml::Table =
        document
            .parse()
            .map_err(|error: toml::de::Error| BuildRefused::CargoManifest {
                directory: directory.to_owned(),
                detail: error.to_string(),
            })?;
    parsed
        .get("package")
        .and_then(|package| package.get("name"))
        .and_then(toml::Value::as_str)
        .map(str::to_owned)
        .ok_or_else(|| BuildRefused::CargoManifest {
            directory: directory.to_owned(),
            detail: "no `package.name` is declared".to_owned(),
        })
}

/// The identifier a crate name is spelled as in Rust source.
fn crate_ident(crate_name: &str) -> String {
    crate_name.replace('-', "_")
}

/// The workspace root every installed package inherits its dependencies from.
///
/// The declared set is what a mod may name, which is what this repository's own
/// `test-mods/` name: the SDK, the host-facing trait a mod implements, and the
/// feature crates for identity, configuration, content, packages and saves,
/// beside the two serialization crates a saved or configured mod cannot be
/// written without. Narrower than that and an installed package inheriting a
/// dependency it inherits here would fail to build on the player's machine
/// alone, which is a mod that passes its author's tests and refuses the launch.
fn workspace_manifest(members: &[PlannedMember], ravel_root: &Path) -> String {
    let mut listed = String::from("\"host\"");
    for member in members {
        write!(listed, ", \"mods/{}\"", member.directory).expect("a string accepts writes");
    }
    let root = ravel_root.display();
    format!(
        "# Generated by ravel-build. Every edit here is overwritten.\n\
         [workspace]\n\
         resolver = \"3\"\n\
         members = [{listed}]\n\
         \n\
         [workspace.package]\n\
         edition = \"2024\"\n\
         license = \"MIT OR Apache-2.0\"\n\
         publish = false\n\
         rust-version = \"1.95\"\n\
         \n\
         [workspace.dependencies]\n\
         jni = \"0.22.4\"\n\
         ravel-config = {{ path = \"{root}/crates/ravel-config\" }}\n\
         ravel-core = {{ path = \"{root}/crates/ravel-core\" }}\n\
         ravel-data = {{ path = \"{root}/crates/ravel-data\" }}\n\
         ravel-host-api = {{ path = \"{root}/crates/ravel-host-api\" }}\n\
         ravel-host-runtime = {{ path = \"{root}/crates/ravel-host-runtime\" }}\n\
         ravel-package = {{ path = \"{root}/crates/ravel-package\" }}\n\
         ravel-save = {{ path = \"{root}/crates/ravel-save\" }}\n\
         ravel-sdk = {{ path = \"{root}/crates/ravel-sdk\" }}\n\
         serde = {{ version = \"1.0.229\", features = [\"derive\"] }}\n\
         serde_json = \"1.0.151\"\n\
         \n\
         [workspace.lints.rust]\n\
         unsafe_code = \"forbid\"\n"
    )
}

fn host_manifest(members: &[PlannedMember]) -> String {
    let mut dependencies = String::new();
    for member in members {
        writeln!(
            dependencies,
            "{} = {{ path = \"../mods/{}\" }}",
            member.crate_name, member.directory
        )
        .expect("a string accepts writes");
    }
    format!(
        "# Generated by ravel-build. Every edit here is overwritten.\n\
         [package]\n\
         name = \"ravel-generated-host\"\n\
         version = \"0.0.0\"\n\
         edition.workspace = true\n\
         license.workspace = true\n\
         publish.workspace = true\n\
         rust-version.workspace = true\n\
         \n\
         [lib]\n\
         name = \"{HOST_LIBRARY}\"\n\
         crate-type = [\"cdylib\", \"rlib\"]\n\
         \n\
         [dependencies]\n\
         jni.workspace = true\n\
         ravel-core.workspace = true\n\
         ravel-host-runtime.workspace = true\n\
         {dependencies}\n\
         [lints]\n\
         workspace = true\n"
    )
}

fn host_source(members: &[PlannedMember]) -> String {
    let mut manifests = String::new();
    let mut pushes = String::new();
    for member in members {
        let constant = member.mod_id.to_uppercase();
        write!(
            manifests,
            "/// The manifest `{mod_id}` ships, read from the package itself.\n\
             const {constant}: &str = include_str!(\"../../mods/{directory}/package.json\");\n\n",
            mod_id = member.mod_id,
            directory = member.directory,
        )
        .expect("a string accepts writes");
        write!(
            pushes,
            "        Member {{\n\
             \x20           package: {constant}.to_owned(),\n\
             \x20           host: {ident}::{ENTRY_FUNCTION}(side),\n\
             \x20       }},\n",
            ident = crate_ident(&member.crate_name),
        )
        .expect("a string accepts writes");
    }
    format!(
        "#![forbid(unsafe_code)]\n\
         \n\
         //! A host generated by `ravel-build` from the packages this instance holds.\n\
         //!\n\
         //! Every edit here is overwritten. What decides the contents is the set of\n\
         //! installed packages, and the way to change it is to install or remove one.\n\
         //!\n\
         //! This file is a member list and a JNI symbol. Resolution, admission and the\n\
         //! lifecycle all belong to `ravel-host-runtime`, which the statically composed\n\
         //! host calls too, so neither host can answer differently from the other.\n\
         \n\
         use jni::EnvUnowned;\n\
         use jni::objects::JClass;\n\
         use ravel_core::Side;\n\
         use ravel_host_runtime::{{Member, initialize}};\n\
         \n\
         {manifests}\
         /// The packages this host was generated from.\n\
         ///\n\
         /// Public because the cdylib is not the only thing that has to be able to\n\
         /// name this set: the JVM enters the symbol below, and a test or a\n\
         /// diagnostic that drives the same members without a JVM needs the list\n\
         /// itself.\n\
         pub fn members(side: Side) -> Vec<Member> {{\n\
         \x20   vec![\n\
         {pushes}\
         \x20   ]\n\
         }}\n\
         \n\
         /// Starts the installed mod set before game methods run.\n\
         #[jni::jni_mangle(\"dev.ravel.jvm.Hook\", \"ravelInitialize\")]\n\
         pub fn ravel_initialize<'local>(mut env: EnvUnowned<'local>, _class: JClass<'local>) {{\n\
         \x20   env.with_env(|env| {{\n\
         \x20       // Asked before the members are built, because a member may be\n\
         \x20       // built differently on each side.\n\
         \x20       let side = ravel_host_runtime::side(env)?;\n\
         \x20       initialize(env, members(side))\n\
         \x20   }})\n\
         \x20   .resolve::<jni::errors::ThrowRuntimeExAndDefault>();\n\
         }}\n"
    )
}

/// Writes a planned host into an instance and compiles it.
///
/// `game_directory` is the instance the packages were discovered in, and
/// `cache` is the build cache the toolchain decision shares per machine. The
/// answer is the built library the JVM loads, copied into the instance: the
/// cache is shared and every instance's host has one name inside it, so the
/// path a launch is given has to be this instance's own copy.
///
/// `minecraft` names the tracked version the host is generated against, and it
/// is an argument because nothing in the instance states it. A package declares
/// `compatibility.minecraft` as a list that may hold ranges and an instance
/// holding no package declares nothing at all, so a version read off the
/// installed set would be a guess where the set is silent and ambiguous where
/// it is not. It is passed to the toolchain rather than left to the environment
/// for the same reason
/// `docs/decisions/version-selection-is-a-build-time-choice.md` refuses a
/// default: a build that inherited the variable would compile whichever version
/// the shell around it happened to name, which on a player's machine is nothing
/// anyone chose.
///
/// A generated file is written only when its bytes differ from what is there,
/// so an unchanged set leaves Cargo nothing to rebuild.
///
/// # Errors
///
/// Returns [`BuildRefused::Write`] when the generated workspace cannot be
/// written, [`BuildRefused::Toolchain`] when Cargo cannot be run at all,
/// [`BuildRefused::Compile`] when it runs and refuses — carrying what it said,
/// with the instance's own path redacted — and [`BuildRefused::MissingArtifact`]
/// when it reports success and the library is not there.
pub fn build(
    plan: &HostPlan,
    game_directory: &Path,
    cache: &Path,
    minecraft: &str,
) -> Result<PathBuf, BuildRefused> {
    let workspace = game_directory.join(WORKSPACE_DIRECTORY);
    for (path, contents) in &plan.files {
        let target = workspace.join(path);
        let parent = target.parent().ok_or_else(|| BuildRefused::Write {
            file: path.clone(),
            detail: "the generated path has no parent".to_owned(),
        })?;
        fs::create_dir_all(parent).map_err(|error| BuildRefused::Write {
            file: path.clone(),
            detail: error.to_string(),
        })?;
        // Rewriting identical bytes would make Cargo rebuild everything that
        // depends on them, which is the whole difference between a warm launch
        // and a cold one.
        if fs::read_to_string(&target).is_ok_and(|existing| existing == *contents) {
            continue;
        }
        fs::write(&target, contents).map_err(|error| BuildRefused::Write {
            file: path.clone(),
            detail: error.to_string(),
        })?;
    }

    let output = Command::new("cargo")
        .arg("build")
        .arg("--release")
        .arg("--manifest-path")
        .arg(workspace.join("host/Cargo.toml"))
        .arg("--target-dir")
        .arg(cache)
        .env(MINECRAFT_VERSION_SELECTION, minecraft)
        .output()
        .map_err(|error| BuildRefused::Toolchain {
            detail: error.to_string(),
        })?;
    if !output.status.success() {
        return Err(BuildRefused::Compile {
            detail: redact(&String::from_utf8_lossy(&output.stderr), game_directory),
        });
    }

    let name = format!("lib{HOST_LIBRARY}.so");
    let built = cache.join("release").join(&name);
    if !built.is_file() {
        return Err(BuildRefused::MissingArtifact { library: name });
    }
    // Copied out of the cache rather than handed back from inside it. The cache
    // is shared per machine and every instance's host is called the same thing,
    // so a path into it names whichever instance built last. The copy is what
    // makes the answer this instance's own.
    let delivered = workspace.join("host").join(&name);
    fs::copy(&built, &delivered).map_err(|error| BuildRefused::Write {
        file: format!("host/{name}"),
        detail: error.to_string(),
    })?;
    Ok(delivered)
}

/// Replaces the instance's own path in text a compiler wrote.
///
/// `SPEC.md` §9.1 requires a report to redact unnecessarily identifying
/// filesystem paths, and a compiler names every file it read. What a player
/// needs from a failed build is which mod and which line, so the text is kept
/// and the directory they keep their game in is not.
fn redact(text: &str, game_directory: &Path) -> String {
    let instance = game_directory.display().to_string();
    if instance.is_empty() {
        return text.to_owned();
    }
    text.replace(&instance, "<instance>")
}

/// Why a host could not be built from what the instance holds.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum BuildRefused {
    /// An installed package carries no `Cargo.toml`, so it names no crate.
    MissingCargoManifest {
        /// The package directory's name.
        directory: String,
    },
    /// An installed package's `Cargo.toml` cannot be read as one.
    CargoManifest {
        /// The package directory's name.
        directory: String,
        /// What the parser or the operating system reported.
        detail: String,
    },
    /// Two installed packages declare one crate name.
    DuplicateCrate {
        /// The name both declare.
        crate_name: String,
        /// The second directory declaring it, in mod-id order.
        directory: String,
        /// The first directory declaring it.
        first: String,
    },
    /// The generated workspace could not be written.
    Write {
        /// The generated file, named relative to the instance.
        file: String,
        /// What the operating system reported.
        detail: String,
    },
    /// The toolchain could not be run at all.
    Toolchain {
        /// What the operating system reported.
        detail: String,
    },
    /// The toolchain ran and refused the installed source.
    Compile {
        /// What it said, with the instance's own path redacted.
        detail: String,
    },
    /// The toolchain reported success and produced no library.
    MissingArtifact {
        /// The library that is not there.
        library: String,
    },
}

impl fmt::Display for BuildRefused {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingCargoManifest { directory } => write!(
                formatter,
                "`{directory}` carries no `Cargo.toml`, so nothing says what crate to build"
            ),
            Self::CargoManifest { directory, detail } => {
                write!(
                    formatter,
                    "`{directory}` declares no buildable crate: {detail}"
                )
            }
            Self::DuplicateCrate {
                crate_name,
                directory,
                first,
            } => write!(
                formatter,
                "`{directory}` builds the crate `{crate_name}`, which `{first}` already builds"
            ),
            Self::Write { file, detail } => {
                write!(formatter, "`{file}` could not be written: {detail}")
            }
            Self::Toolchain { detail } => write!(
                formatter,
                "the Rust toolchain that compiles installed mods could not be run: {detail}"
            ),
            Self::Compile { detail } => {
                write!(formatter, "the installed mods did not compile:\n{detail}")
            }
            Self::MissingArtifact { library } => write!(
                formatter,
                "the build reported success and produced no `{library}`"
            ),
        }
    }
}

impl std::error::Error for BuildRefused {}

impl StructuredFailure for BuildRefused {
    /// No variant is one of `SPEC.md` §9.2's dependency-graph outcomes. A build
    /// happens after the set has a legal order and says nothing about the graph.
    fn failure_kind(&self) -> Option<FailureKind> {
        None
    }

    /// Every refusal here is a package that was validated and whose code was
    /// never made available, which is the step [`LifecycleState::Loaded`] is the
    /// far side of.
    fn lifecycle_state(&self) -> LifecycleState {
        LifecycleState::Validated
    }

    /// The two that quote a tool: a Cargo manifest an author wrote, and the
    /// compiler's own report about their source.
    fn quotes_untrusted_text(&self) -> bool {
        match self {
            Self::CargoManifest { .. } | Self::Compile { .. } | Self::Toolchain { .. } => true,
            Self::MissingCargoManifest { .. }
            | Self::DuplicateCrate { .. }
            | Self::Write { .. }
            | Self::MissingArtifact { .. } => false,
        }
    }
}

