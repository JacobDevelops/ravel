#![forbid(unsafe_code)]

//! Builds a host on the player's machine from the packages they installed.
//!
//! ADG-2 makes a mod's code Rust source, so a discovered package has a manifest
//! and no value: nothing to construct and nothing to enter. That is why a launch
//! could find an installed package and still refuse it. This crate is the step
//! between — it writes a Cargo workspace that names the installed packages, and
//! compiles it into the host binary the JVM loads.
//!
//! # What it generates
//!
//! Three files, under the instance's own `ravel` directory:
//!
//! - `Cargo.toml`, a workspace root whose members are the generated host and
//!   every installed package. It sits above `mods/` so that a package's own
//!   `Cargo.toml` can inherit `edition`, `license` and the Ravel dependencies
//!   from it. That is what lets an installed mod's manifest be byte-identical to
//!   the ones under `test-mods/` here: `ravel-sdk.workspace = true`.
//! - `host/Cargo.toml`, one cdylib named `ravel_bootstrap` — the name the JVM
//!   loads, and the same one [`ravel-composed-host`] produces.
//! - `host/src/lib.rs`, a member list and a JNI entry point that calls
//!   [`ravel_host_runtime::initialize`]. Nothing else. The generated host does
//!   not resolve, admit or drive anything itself, because a second route to a
//!   `LifecycleEntry` could answer differently from the first.
//!
//! # How a package's value is reached
//!
//! [`plan`] reads each package's `Cargo.toml` for its crate name, and the
//! generated host calls `<crate>::__ravel_entry()` — the function
//! `ravel_sdk::export_mod!` writes. A package that exports no entry fails the
//! compile naming its own crate, which is a refusal rather than a host quietly
//! one mod smaller.
//!
//! # Determinism
//!
//! The generated bytes are a function of the discovered set — each package's mod
//! id, its directory, its crate name — and of where Ravel's own crates live.
//! Packages are visited in the order [`ravel_loader::discover`] answers in, which
//! is mod-id order, so two runs over one instance write one byte sequence.
//! [`HostPlan::fingerprint`] is the digest of those bytes.
//!
//! # Staying warm
//!
//! [`build`] writes a generated file only when its bytes differ from what is
//! already there, and compiles into a build cache that
//! `docs/decisions/shared-toolchain-and-build-cache.md` decided is shared per
//! machine. An unchanged set therefore rewrites nothing and Cargo has nothing to
//! rebuild: `evidence/m3/pack-compile.json` measured that path at about 1.6
//! seconds for a 256-mod pack against about 32 seconds cold.

