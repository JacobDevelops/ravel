    /// Everything that needs a real compiler, in one test.
    ///
    /// Every other test here asserts generated bytes and never runs Cargo. This
    /// one runs it, and it is one test rather than five on purpose: `nextest`
    /// gives each test its own process, so tests cannot share a build cache
    /// unless it sits at a fixed path — and a gate that writes to a fixed cache
    /// mutates state shared with whatever else has run on the machine, including
    /// the player-facing cache the toolchain decision is about. The cache below
    /// is this process's own and is deleted at the end, which costs one cold
    /// build per gate run and no shared state at all.
    ///
    /// What it proves, in order: an installed package compiles into the library
    /// the JVM loads; that library exports the symbol the JVM resolves; the
    /// mod's own code is entered in a process; an unchanged instance stays warm;
    /// a second instance does not take the first one's host; and a package that
    /// cannot be built refuses instead of yielding a smaller host.
    #[test]
    fn the_installed_set_is_compiled_into_a_host_that_runs_the_packages_it_names() {
        let cache = std::env::temp_dir().join(format!("ravel-build-cache-{}", std::process::id()));
        let outcome = std::panic::catch_unwind(|| compiling_proof(&cache));
        let _ = fs::remove_dir_all(&cache);
        if let Err(panic) = outcome {
            std::panic::resume_unwind(panic);
        }
    }

    fn compiling_proof(cache: &Path) {
        let instance = instance("built");
        install(
            &instance,
            "installed-1.0.0",
            "installed_mod",
            "installed-mod",
            EXPORTING_SOURCE,
        );
        // Installed beside it because most mods name more than the SDK, and a
        // generated workspace that declares only the SDK builds this one
        // nowhere but in the repository the author wrote it in.
        install_with(
            &instance,
            "host-api-1.0.0",
            "host_api_mod",
            "host-api-mod",
            HOST_API_SOURCE,
            "ravel-core.workspace = true\n\
             ravel-host-api.workspace = true\n\
             ravel-sdk.workspace = true\n",
        );

        let plan = planned(&instance);
        let library =
            build(&plan, &instance, cache, &game()).expect("the installed package compiles");

        assert!(library.is_file(), "{}", library.display());
        assert_eq!(
            library.file_name().and_then(std::ffi::OsStr::to_str),
            Some(format!("lib{HOST_LIBRARY}.so").as_str())
        );

        // The symbol the JVM looks up. A library that built and exports nothing
        // is a host the game loads and never enters, which would pass every
        // assertion above.
        let bytes = fs::read(&library).expect("the built library is readable");
        assert!(
            holds(&bytes, ENTRY_SYMBOL),
            "the built host exports no `{ENTRY_SYMBOL}`"
        );

        drives_the_package_it_was_built_from(&instance, cache);

        // Built a second time from an unchanged instance. The generated files
        // are rewritten only when their bytes differ, so this is the warm path
        // rather than a second cold build.
        let written = generated_times(&plan, &instance);
        let again =
            build(&plan, &instance, cache, &game()).expect("an unchanged instance rebuilds");
        assert_eq!(again, library);
        assert_eq!(
            written,
            generated_times(&plan, &instance),
            "an unchanged instance rewrote its generated source, which makes every launch cold"
        );

        a_second_instance_keeps_its_own_host(&library, cache);
        a_package_that_names_no_value_refuses(cache);
        a_version_naming_no_tracked_directory_refuses(&plan, &instance, cache);
        fs::remove_dir_all(&instance).expect("cleanup");
    }

    /// The version is this build's input, not whatever the shell was holding.
    ///
    /// The same plan and the same instance that compiled above are compiled
    /// again with a version no tracked directory carries. A build that inherited
    /// its selection would ignore the argument and succeed exactly as it just
    /// did, so the refusal is the whole evidence that the argument is what the
    /// toolchain reads — and the message it carries names the selection and the
    /// versions that do exist, which is what a player can act on.
    fn a_version_naming_no_tracked_directory_refuses(
        plan: &super::HostPlan,
        instance: &Path,
        cache: &Path,
    ) {
        let refused = build(plan, instance, cache, "no-tracked-directory-carries-this")
            .expect_err("the selected version names no tracked directory");
        let BuildRefused::Compile { detail } = &refused else {
            panic!("the refusal should be the toolchain's: {refused:?}");
        };
        assert!(
            detail.contains(MINECRAFT_VERSION_SELECTION),
            "the refusal does not name the selection: {detail}"
        );
        assert!(
            detail.contains("no-tracked-directory-carries-this"),
            "the refusal does not name the version that was asked for: {detail}"
        );
        assert!(
            detail.contains(&game()),
            "the refusal does not name a version that is tracked: {detail}"
        );
    }

    /// The question this work package is actually about.
    ///
    /// A host that builds proves the compiler accepted the source. It does not
    /// prove that a package no Ravel developer compiled is *constructed and
    /// entered*, and that is the row's claim. So the generated host is driven in
    /// a process here: a small program links it as a library, hands its
    /// `members()` to the same [`ravel_host_runtime::compose`] a launch calls,
    /// and the mod records — from inside its own body — that it reached
    /// `register` and `running`. The evidence is written by the installed mod
    /// and read by this test, so nothing but the mod's own execution can produce
    /// it.
    ///
    /// What is still missing is the JVM. This drives the host without one, which
    /// is why the symbol assertion above exists beside it.
    fn drives_the_package_it_was_built_from(instance: &Path, cache: &Path) {
        let driver = instance.join("driver");
        fs::create_dir_all(driver.join("src")).expect("a driver directory is creatable");
        let root = ravel_root();
        fs::write(
            driver.join("Cargo.toml"),
            format!(
                "[workspace]\n\
                 \n\
                 [package]\n\
                 name = \"ravel-build-driver\"\n\
                 version = \"0.0.0\"\n\
                 edition = \"2024\"\n\
                 \n\
                 [dependencies]\n\
                 ravel-core = {{ path = \"{root}/crates/ravel-core\" }}\n\
                 ravel-generated-host = {{ path = \"../ravel/host\" }}\n\
                 ravel-host-runtime = {{ path = \"{root}/crates/ravel-host-runtime\" }}\n",
                root = root.display()
            ),
        )
        .expect("the driver manifest is writable");
        fs::write(
            driver.join("src/main.rs"),
            "fn main() {\n\
             \x20   let game = std::env::args().nth(1).expect(\"a game directory\");\n\
             \x20   // The library name the generated host declares, which is the\n\
             \x20   // name the JVM loads and therefore the name a dependent links.\n\
             \x20   let members = ravel_bootstrap::members(ravel_core::Side::Client);\n\
             \x20   let (machine, _, _) = ravel_host_runtime::compose(\n\
             \x20       std::path::Path::new(&game),\n\
             \x20       ravel_core::Side::Client,\n\
             \x20       members,\n\
             \x20   )\n\
             \x20   .expect(\"the generated host composes\");\n\
             \x20   for id in machine.order() {\n\
             \x20       println!(\"{id}\");\n\
             \x20   }\n\
             }\n",
        )
        .expect("the driver source is writable");

        let built = Command::new("cargo")
            .arg("build")
            .arg("--release")
            .arg("--manifest-path")
            .arg(driver.join("Cargo.toml"))
            .arg("--target-dir")
            .arg(cache)
            .output()
            .expect("cargo runs");
        assert!(
            built.status.success(),
            "the driver did not build: {}",
            String::from_utf8_lossy(&built.stderr)
        );

        let marks = instance.join("marks");
        let run = Command::new(cache.join("release/ravel-build-driver"))
            .arg(instance)
            .env("RAVEL_PROOF", &marks)
            .output()
            .expect("the driver runs");
        assert!(
            run.status.success(),
            "the generated host refused to compose: {}",
            String::from_utf8_lossy(&run.stderr)
        );
        assert!(
            String::from_utf8_lossy(&run.stdout).contains("installed_mod"),
            "the driven set does not hold the installed package: {}",
            String::from_utf8_lossy(&run.stdout)
        );
        assert!(
            String::from_utf8_lossy(&run.stdout).contains("host_api_mod"),
            "the driven set does not hold the package naming `ravel-host-api`: {}",
            String::from_utf8_lossy(&run.stdout)
        );

        // Written by the mod, from inside its own body, in another process.
        let recorded = fs::read_to_string(&marks).expect("the installed mod recorded nothing");
        assert!(
            recorded.contains("register"),
            "a package no Ravel developer compiled never reached `register`: {recorded}"
        );
        assert!(
            recorded.contains("running"),
            "a package no Ravel developer compiled never reached `running`: {recorded}"
        );
        // The package that names the host-facing surface rather than the SDK
        // alone. It compiled, so the generated workspace declared what it
        // inherits, and it ran, so the dependency it inherited was the right one.
        assert!(
            recorded.contains("host-api running"),
            "the package naming `ravel-host-api` never reached `running`: {recorded}"
        );
    }

    /// Two instances on one machine do not hand each other their hosts.
    ///
    /// The build cache is shared per machine and every generated host is called
    /// the same thing inside it, so the library a launch is given has to be the
    /// one this instance built. Building the second instance would otherwise
    /// silently replace the first instance's host with a set of mods it never
    /// installed.
    fn a_second_instance_keeps_its_own_host(first: &Path, cache: &Path) {
        let second = instance("second-instance");
        install(
            &second,
            "beta-1.0.0",
            "beta_mod",
            "beta-mod",
            EXPORTING_SOURCE,
        );

        let beta =
            build(&planned(&second), &second, cache, &game()).expect("the second instance builds");
        assert_ne!(first, beta);

        let bytes = fs::read(first).expect("the first instance's host is readable");
        assert!(
            holds(&bytes, "installed_mod"),
            "the first host lost its own mod"
        );
        assert!(
            !holds(&bytes, "beta_mod"),
            "the first instance was handed the second instance's host"
        );
        fs::remove_dir_all(&second).expect("cleanup");
    }

    /// A package that will not compile refuses, and says which one and why.
    fn a_package_that_names_no_value_refuses(cache: &Path) {
        let instance = instance("silent");
        install(
            &instance,
            "installed-1.0.0",
            "installed_mod",
            "installed-mod",
            EXPORTING_SOURCE,
        );
        install(
            &instance,
            "silent-1.0.0",
            "silent_mod",
            "silent-mod",
            SILENT_SOURCE,
        );

        let plan = planned(&instance);
        let refused =
            build(&plan, &instance, cache, &game()).expect_err("one package names no value");
        let BuildRefused::Compile { detail } = &refused else {
            panic!("the refusal should be the compiler's: {refused:?}");
        };
        assert!(detail.contains("__ravel_entry"), "{detail}");
        assert!(detail.contains("silent_mod"), "{detail}");
        // And it does not say where the player keeps their game.
        assert!(
            !detail.contains(&instance.display().to_string()),
            "the refusal names the instance path"
        );
        assert!(detail.contains("<instance>"), "{detail}");
        assert!(refused.quotes_untrusted_text());
        fs::remove_dir_all(&instance).expect("cleanup");
    }

    fn holds(bytes: &[u8], needle: &str) -> bool {
        bytes
            .windows(needle.len())
            .any(|window| window == needle.as_bytes())
    }

    fn generated_times(plan: &super::HostPlan, instance: &Path) -> Vec<std::time::SystemTime> {
        plan.files()
            .keys()
            .map(|path| {
                fs::metadata(instance.join(WORKSPACE_DIRECTORY).join(path))
                    .and_then(|meta| meta.modified())
                    .expect("a generated file was written")
            })
            .collect()
    }
