use crate::loaded::LoadedMods;

/// Layers ordinary files last-wins and merges tag members in mod load order.
/// A required owner failure blocks collection before any declaration callback is invoked.
///
/// # Errors
///
/// Records callback failures and skips optional owners before world mutation.
/// Returns [`ResourceRefused`] for a required failure, a halted set, or failed attribution.
pub fn open_resources<H: std::ops::DerefMut<Target: Mod>>(
    loaded: &mut LoadedMods<'_, H>,
    environment: &FailureEnvironment,
) -> Result<Supplied, ResourceRefused> {
    let (machine, mods) = loaded.parts();
    if let Some(by) = crate::events::active_blocker(machine) {
        return Err(ResourceRefused::Halted { by: by.clone() });
    }
    let eligible: Vec<_> = machine
        .eligible()
        .map(|(entry, state)| {
            (
                entry.mod_id.clone(),
                state,
                entry.sides.loads_on(machine.side().world_side()),
            )
        })
        .collect();
    let mut generated = Vec::with_capacity(eligible.len());
    let mut tags = TagResources::default();
    for (mod_id, state, world_eligible) in eligible {
        let instance = crate::loaded::instance(mods, &mod_id);
        let declaration = match crate::callback(&mod_id, state, || instance.content_declaration()) {
            Ok(Some(declaration)) => declaration,
            Ok(None) => continue,
            Err(source) => {
                crate::lifecycle::isolate(
                    machine,
                    environment,
                    source,
                    ResourceRefused::Lifecycle,
                    |source| ResourceRefused::Mod { mod_id, source },
                )?;
                continue;
            }
        };
        match generate(&mod_id, &declaration, world_eligible) {
            Ok((files, contributions)) => {
                tags.append(contributions);
                generated.push((mod_id, files));
            }
            Err(refused) => crate::lifecycle::isolate_loader_refusal(
                machine,
                environment,
                &mod_id,
                refused,
                ResourceRefused::Lifecycle,
            )?,
        }
    }

    Ok(supplied(generated, &tags))
}

fn generate(
    mod_id: &ModId,
    declaration: &ravel_data::ContentDeclaration,
    world_eligible: bool,
) -> Result<(GeneratedData, TagResources), ResourceRefused> {
    if declaration.owner() != mod_id {
        return Err(ResourceRefused::ForeignDeclaration {
            mod_id: mod_id.clone(),
            owner: declaration.owner().clone(),
        });
    }
    let mut files = declaration.generate();
    if !world_eligible {
        files.retain(|path| path.first_segment() != "data");
    }
    let tags = TagResources::from_generated(mod_id, &files).map_err(ResourceRefused::Tag)?;
    Ok((files, tags))
}

fn supplied(generated: Vec<(ModId, GeneratedData)>, tags: &TagResources) -> Supplied {
    let merged = tags;
    let set = ResourceSet::layered(generated.iter().map(|(owner, files)| {
        (
            owner,
            files
                .files()
                .iter()
                .map(GeneratedFile::path)
                .filter(move |path| {
                    merged
                        .supplier(path)
                        .is_none_or(|supplier| supplier == owner)
                }),
        )
    }));
    let at = generated
        .iter()
        .enumerate()
        .map(|(index, (owner, _))| (owner.clone(), index))
        .collect();
    let tag_replacements = tags.replacements().to_vec();
    let tags = tags.generate();
    Supplied {
        generated,
        at,
        set,
        tags,
        tag_replacements,
    }
}

/// Layered resources and their generated bytes, retained once per launch.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct Supplied {
    generated: Vec<(ModId, GeneratedData)>,
    // Index owners without changing the resolved order in `generated`.
    at: BTreeMap<ModId, usize>,
    set: ResourceSet,
    tags: GeneratedData,
    tag_replacements: Vec<ravel_data::Override>,
}

impl Supplied {
    /// Returns the last contributor for tags, ordinary suppliers, and ordinary overrides.
    #[must_use]
    pub const fn set(&self) -> &ResourceSet {
        &self.set
    }

    /// Returns explicit tag replacements, naming discarded contributors and the replacing mod.
    #[must_use]
    pub fn tag_replacements(&self) -> &[ravel_data::Override] {
        &self.tag_replacements
    }

    /// Returns each mod's side-admitted generated files, before launch-wide tag merging.
    #[must_use]
    pub fn generated(&self) -> &[(ModId, GeneratedData)] {
        &self.generated
    }

    /// Returns the bytes the game reads: merged tags or the winning ordinary resource.
    #[must_use]
    pub fn bytes(&self, path: &RelativePath) -> Option<&[u8]> {
        if let Some(file) = self.tags.file(path) {
            return Some(file.bytes());
        }
        let supplier = self.set.supplier(path)?;
        self.generated
            .get(*self.at.get(supplier)?)
            .and_then(|(_, files)| files.file(path))
            .map(GeneratedFile::bytes)
    }
}

/// Why an admitted set's files could not be layered.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ResourceRefused {
    /// The lifecycle refused failure attribution.
    Lifecycle(crate::LifecycleError),
    /// A required failure or halted set blocks content callbacks.
    Halted {
        /// The mod whose failure blocks the set.
        by: ModId,
    },
    /// A mod refused to declare its content.
    Mod {
        /// The mod that refused.
        mod_id: ModId,
        /// Its refusal.
        source: HostError,
    },
    /// A mod supplied a malformed tag document.
    Tag(ravel_data::TagResourceError),
    /// A mod handed over a declaration owned by another identity.
    ForeignDeclaration {
        /// The mod that handed it over.
        mod_id: ModId,
        /// The identity the declaration names as its owner.
        owner: ModId,
    },
}

impl ResourceRefused {
    /// Returns the mod this refusal is about, when one is known.
    #[must_use]
    pub fn mod_id(&self) -> Option<&ModId> {
        match self {
            Self::Lifecycle(error) => error.mod_id(),
            Self::Halted { by } => Some(by),
            Self::Tag(error) => Some(&error.mod_id),
            Self::Mod { mod_id, .. } | Self::ForeignDeclaration { mod_id, .. } => Some(mod_id),
        }
    }
}

impl fmt::Display for ResourceRefused {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Lifecycle(error) => error.fmt(formatter),
            Self::Halted { by } => write!(formatter, "the mod set is blocked after `{by}` failed"),
            Self::Mod { mod_id, source } => {
                write!(
                    formatter,
                    "`{mod_id}` refused its content declaration: {source}"
                )
            }
            Self::Tag(error) => error.fmt(formatter),
            Self::ForeignDeclaration { mod_id, owner } => write!(
                formatter,
                "`{mod_id}` supplies content declared as `{owner}`'s, so its files would be filed \
                 under a namespace it does not own"
            ),
        }
    }
}

impl std::error::Error for ResourceRefused {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Lifecycle(error) => Some(error),
            Self::Mod { source, .. } => Some(source),
            Self::Tag(error) => Some(error),
            Self::Halted { .. } | Self::ForeignDeclaration { .. } => None,
        }
    }
}

impl StructuredFailure for ResourceRefused {
    fn failure_kind(&self) -> Option<FailureKind> {
        match self {
            Self::Lifecycle(error) => error.failure_kind(),
            Self::Mod { source, .. } => source.failure_kind(),
            Self::Halted { .. } | Self::ForeignDeclaration { .. } | Self::Tag(_) => None,
        }
    }

    fn lifecycle_state(&self) -> LifecycleState {
        match self {
            Self::Lifecycle(error) => error.lifecycle_state(),
            Self::Mod { source, .. } => source.lifecycle_state(),
            Self::Halted { .. } => LifecycleState::Failed,
            Self::ForeignDeclaration { .. } | Self::Tag(_) => LifecycleState::Registered,
        }
    }

    fn quotes_untrusted_text(&self) -> bool {
        match self {
            Self::Lifecycle(error) => error.quotes_untrusted_text(),
            Self::Mod { source, .. } => source.quotes_untrusted_text(),
            Self::Tag(_) => true,
            Self::Halted { .. } | Self::ForeignDeclaration { .. } => false,
        }
    }
}

