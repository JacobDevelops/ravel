use std::collections::BTreeMap;
use std::fmt;

use ravel_core::{
    FailureEnvironment, FailureKind, LifecycleState, ModId, RelativePath, StructuredFailure,
};
use ravel_data::{GeneratedData, GeneratedFile, ResourceSet};
use ravel_host_api::{HostError, Mod};

use crate::loaded::LoadedMods;

/// Layers files from mods on this side in load order; later suppliers win contested paths.
///
/// # Errors
///
/// Records callback failures and skips optional owners before world mutation.
/// Returns [`ResourceRefused`] for a required failure, a halted set, or failed attribution.
pub fn open_resources<H: std::ops::DerefMut<Target: Mod>>(
    loaded: &mut LoadedMods<'_, H>,
    environment: &FailureEnvironment,
) -> Result<Supplied, ResourceRefused> {
    let (machine, mods) = loaded.parts();
    let eligible: Vec<_> = machine
        .eligible()
        .map(|(entry, state)| (entry.mod_id.clone(), state))
        .collect();
    let mut generated = Vec::with_capacity(eligible.len());
    for (mod_id, state) in eligible {
        let instance = crate::loaded::instance(mods, &mod_id);
        let declaration = match crate::callback(&mod_id, state, || instance.content_declaration()) {
            Ok(Some(declaration)) => declaration,
            Ok(None) => continue,
            Err(source) => {
                crate::lifecycle::isolate(
                    machine,
                    environment,
                    source,
                    ResourceRefused::Lifecycle,
                    |source| ResourceRefused::Mod { mod_id, source },
                )?;
                continue;
            }
        };
        if declaration.owner() != &mod_id {
            let refused = ResourceRefused::ForeignDeclaration {
                mod_id: mod_id.clone(),
                owner: declaration.owner().clone(),
            };
            crate::lifecycle::isolate_foreign(
                machine,
                environment,
                &mod_id,
                refused,
                ResourceRefused::Lifecycle,
            )?;
            continue;
        }
        generated.push((mod_id.clone(), declaration.generate()));
    }

    let set = ResourceSet::layered(
        generated
            .iter()
            .map(|(owner, files)| (owner, files.files().iter().map(GeneratedFile::path))),
    );

    let at = generated
        .iter()
        .enumerate()
        .map(|(index, (owner, _))| (owner.clone(), index))
        .collect();
    Ok(Supplied { generated, at, set })
}

/// Layered resources and their generated bytes, retained once per launch.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct Supplied {
    generated: Vec<(ModId, GeneratedData)>,
    // Index owners without changing the resolved order in `generated`.
    at: BTreeMap<ModId, usize>,
    set: ResourceSet,
}

impl Supplied {
    /// Returns which mod supplies each path, and every override it recorded.
    #[must_use]
    pub const fn set(&self) -> &ResourceSet {
        &self.set
    }

    /// Returns each mod's generated pack, in the load order it was asked in.
    #[must_use]
    pub fn generated(&self) -> &[(ModId, GeneratedData)] {
        &self.generated
    }

    /// Returns the bytes the game reads at `path`, from the mod that supplies it.
    #[must_use]
    pub fn bytes(&self, path: &RelativePath) -> Option<&[u8]> {
        let supplier = self.set.supplier(path)?;
        self.generated
            .get(*self.at.get(supplier)?)
            .and_then(|(_, files)| files.file(path))
            .map(GeneratedFile::bytes)
    }
}

/// Why an admitted set's files could not be layered.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ResourceRefused {
    /// The lifecycle refused failure attribution.
    Lifecycle(crate::LifecycleError),
    /// A mod refused to declare its content.
    Mod {
        /// The mod that refused.
        mod_id: ModId,
        /// Its refusal.
        source: HostError,
    },
    /// A mod handed over a declaration owned by another identity.
    ForeignDeclaration {
        /// The mod that handed it over.
        mod_id: ModId,
        /// The identity the declaration names as its owner.
        owner: ModId,
    },
}

impl ResourceRefused {
    /// Returns the mod this refusal is about, when one is known.
    #[must_use]
    pub const fn mod_id(&self) -> Option<&ModId> {
        match self {
            Self::Lifecycle(_) => None,
            Self::Mod { mod_id, .. } | Self::ForeignDeclaration { mod_id, .. } => Some(mod_id),
        }
    }
}

impl fmt::Display for ResourceRefused {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Lifecycle(error) => error.fmt(formatter),
            Self::Mod { mod_id, source } => {
                write!(
                    formatter,
                    "`{mod_id}` refused its content declaration: {source}"
                )
            }
            Self::ForeignDeclaration { mod_id, owner } => write!(
                formatter,
                "`{mod_id}` supplies content declared as `{owner}`'s, so its files would be filed \
                 under a namespace it does not own"
            ),
        }
    }
}

impl std::error::Error for ResourceRefused {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Lifecycle(error) => Some(error),
            Self::Mod { source, .. } => Some(source),
            Self::ForeignDeclaration { .. } => None,
        }
    }
}

impl StructuredFailure for ResourceRefused {
    fn failure_kind(&self) -> Option<FailureKind> {
        match self {
            Self::Lifecycle(error) => error.failure_kind(),
            Self::Mod { source, .. } => source.failure_kind(),
            Self::ForeignDeclaration { .. } => None,
        }
    }

    fn lifecycle_state(&self) -> LifecycleState {
        match self {
            Self::Lifecycle(error) => error.lifecycle_state(),
            Self::Mod { source, .. } => source.lifecycle_state(),
            Self::ForeignDeclaration { .. } => LifecycleState::Registered,
        }
    }

    fn quotes_untrusted_text(&self) -> bool {
        match self {
            Self::Lifecycle(error) => error.quotes_untrusted_text(),
            Self::Mod { source, .. } => source.quotes_untrusted_text(),
            Self::ForeignDeclaration { .. } => false,
        }
    }
}

#[cfg(test)]
mod tests {
    use ravel_core::{ContentKind, LifecycleState, ModId, RelativePath, Side};
    use ravel_data::ContentDeclaration;
    use ravel_host_api::{HostError, Mod};

    use super::ResourceRefused;

    fn open_resources<H: std::ops::DerefMut<Target: Mod>>(
        loaded: &mut crate::LoadedMods<'_, H>,
    ) -> Result<super::Supplied, ResourceRefused> {
        super::open_resources(loaded, &crate::tests::environment())
    }
    use crate::lifecycle::{LifecycleEntry, LifecycleMachine};
    use crate::tests::entry;

    fn id(name: &str) -> ModId {
        name.parse().expect("a legal mod id")
    }

    fn path(text: &str) -> RelativePath {
        RelativePath::try_from(text.to_owned()).expect("a legal relative path")
    }

    struct Supplying {
        id: ModId,
        declared_owner: ModId,
        supplies: Vec<(RelativePath, Vec<u8>)>,
        refuses_declaration: bool,
        calls: std::cell::Cell<usize>,
        fails_start: bool,
    }

    impl Supplying {
        fn new(name: &str, supplies: &[(&str, &str)]) -> Self {
            Self {
                id: id(name),
                declared_owner: id(name),
                refuses_declaration: false,
                calls: std::cell::Cell::new(0),
                fails_start: false,
                supplies: supplies
                    .iter()
                    .map(|(at, bytes)| (path(at), (*bytes).as_bytes().to_vec()))
                    .collect(),
            }
        }

        fn declaring_for(mut self, other: &str) -> Self {
            self.declared_owner = id(other);
            self
        }
    }

    impl Mod for Supplying {
        fn id(&self) -> &ModId {
            &self.id
        }

        fn enter(&mut self, _state: LifecycleState) -> Result<(), ravel_host_api::ModError> {
            if self.fails_start {
                return Err(ravel_host_api::ModError::Unsupported);
            }
            Ok(())
        }

        fn content_declaration(
            &self,
        ) -> Result<Option<std::borrow::Cow<'_, ContentDeclaration>>, ravel_host_api::ModError>
        {
            self.calls.set(self.calls.get() + 1);
            if self.refuses_declaration {
                return Err(ravel_host_api::ModError::Unsupported);
            }
            let mut declaration = ContentDeclaration::new(self.declared_owner.clone());
            declaration
                .entry(ContentKind::Item, "thing")
                .expect("a legal, undeclared entry");
            for (at, bytes) in &self.supplies {
                declaration
                    .resource(at.clone(), bytes.clone())
                    .expect("each path is supplied once");
            }
            Ok(Some(std::borrow::Cow::Owned(declaration)))
        }
    }

    struct Silent {
        id: ModId,
    }

    impl Mod for Silent {
        fn id(&self) -> &ModId {
            &self.id
        }

        fn enter(&mut self, _state: LifecycleState) -> Result<(), ravel_host_api::ModError> {
            Ok(())
        }
    }

    fn machine(entries: Vec<LifecycleEntry>) -> LifecycleMachine {
        LifecycleMachine::new(Side::DedicatedServer, entries).expect("a legal plan")
    }

    #[test]
    fn content_declaration_refusal_is_not_absence() {
        let mut host = Supplying::new("refusing_mod", &[]);
        host.refuses_declaration = true;
        let mut machine = machine(vec![entry("refusing_mod", &[Side::DedicatedServer])]);
        assert_eq!(
            open_resources(
                &mut crate::LoadedMods::<Box<dyn Mod>>::new(&mut machine, &mut [Box::new(host)])
                    .expect("complete host set")
            ),
            Err(ResourceRefused::Mod {
                mod_id: id("refusing_mod"),
                source: HostError::Unsupported {
                    mod_id: id("refusing_mod"),
                    state: LifecycleState::Discovered,
                },
            })
        );
    }

    #[test]
    fn an_optional_declaration_failure_records_and_preserves_later_resources() {
        let mut failed = Supplying::new("failed_mod", &[]);
        failed.refuses_declaration = true;
        let mut later = Supplying::new("later_mod", &[("assets/later.json", "healthy")]);
        let mut optional = entry("failed_mod", &[Side::DedicatedServer]);
        optional.requirement = crate::Requirement::Optional;
        let mut machine = machine(vec![optional, entry("later_mod", &[Side::DedicatedServer])]);
        let supplied = open_resources(
            &mut crate::LoadedMods::<&mut dyn Mod>::new(
                &mut machine,
                &mut [&mut failed, &mut later],
            )
            .expect("complete mod set"),
        )
        .expect("optional refusal does not hide healthy resources");
        assert_eq!(
            supplied.bytes(&path("assets/later.json")),
            Some(b"healthy".as_slice())
        );
        assert_eq!(supplied.generated().len(), 1);
        assert_eq!(machine.state(&id("failed_mod")), Ok(LifecycleState::Failed));
        let failure = machine
            .failure(&id("failed_mod"))
            .expect("tracked")
            .expect("recorded");
        assert_eq!(failure.mod_id.as_ref(), Some(&id("failed_mod")));
        assert_eq!(failure.environment, crate::tests::environment());
        assert_eq!(failed.calls.get(), 1);
        assert_eq!(later.calls.get(), 1);
    }

    #[test]
    fn every_declaring_mod_supplies_its_files_and_a_silent_one_supplies_none() {
        let mut mods: Vec<Box<dyn Mod>> = vec![
            Box::new(Supplying::new("first_mod", &[("assets/first.json", "1")])),
            Box::new(Silent { id: id("mute_mod") }),
        ];
        let mut machine = machine(vec![
            entry("first_mod", &[Side::DedicatedServer]),
            entry("mute_mod", &[Side::DedicatedServer]),
        ]);

        let supplied = open_resources(
            &mut crate::LoadedMods::<Box<dyn Mod>>::new(&mut machine, &mut mods)
                .expect("complete host set"),
        )
        .expect("both mods are legal");

        assert_eq!(
            supplied.set().supplier(&path("assets/first.json")),
            Some(&id("first_mod"))
        );
        assert_eq!(
            supplied.bytes(&path("assets/first.json")),
            Some(b"1".as_ref())
        );
        assert_eq!(
            supplied.generated().len(),
            1,
            "a silent mod generates nothing"
        );
        assert_eq!(supplied.set().overrides(), []);
    }

    #[test]
    fn the_mod_later_in_load_order_supplies_a_contested_path() {
        let shared = "assets/shared/lang/en_us.json";
        let contested = path(shared);

        for (first, second) in [("base_mod", "skin_mod"), ("skin_mod", "base_mod")] {
            let mut mods: Vec<Box<dyn Mod>> = vec![
                Box::new(Supplying::new(first, &[(shared, first)])),
                Box::new(Supplying::new(second, &[(shared, second)])),
            ];
            let mut machine = machine(vec![
                entry(first, &[Side::DedicatedServer]),
                entry(second, &[Side::DedicatedServer]),
            ]);

            let supplied = open_resources(
                &mut crate::LoadedMods::<Box<dyn Mod>>::new(&mut machine, &mut mods)
                    .expect("complete host set"),
            )
            .expect("both mods are legal");

            assert_eq!(
                supplied.set().supplier(&contested),
                Some(&id(second)),
                "`{second}` loads last"
            );
            assert_eq!(supplied.bytes(&contested), Some(second.as_bytes()));
            let overrides = supplied.set().overrides();
            assert_eq!(overrides.len(), 1);
            assert_eq!(overrides[0].winner, id(second));
            assert_eq!(
                overrides[0].shadowed,
                [id(first)],
                "the shadowed mod is named"
            );
        }
    }

    #[test]
    fn a_parked_mod_supplies_nothing_on_the_side_it_does_not_load_on() {
        let mut mods: Vec<Box<dyn Mod>> = vec![Box::new(Supplying::new(
            "client_mod",
            &[("assets/client.json", "c")],
        ))];
        let mut machine = machine(vec![entry("client_mod", &[Side::Client])]);

        let supplied = open_resources(
            &mut crate::LoadedMods::<Box<dyn Mod>>::new(&mut machine, &mut mods)
                .expect("complete host set"),
        )
        .expect("a parked mod refuses nothing");

        assert_eq!(supplied.generated(), []);
        assert_eq!(supplied.bytes(&path("assets/client.json")), None);
    }

    #[test]
    fn failed_optional_owners_neither_declare_nor_supply_resources() {
        let mut host = Supplying::new("failed_mod", &[("assets/failed.json", "bad")]);
        host.fails_start = true;
        let mut planned = entry("failed_mod", &[Side::DedicatedServer]);
        planned.requirement = crate::Requirement::Optional;
        let mut machine = machine(vec![planned]);
        let environment = ravel_core::FailureEnvironment {
            ravel: "0.1.0".parse().expect("valid version"),
            minecraft: "test".to_owned(),
            platform: "test".to_owned(),
            architecture: "test".to_owned(),
        };
        let mut hosts: [&mut dyn Mod; 1] = [&mut host];
        let mut loaded = crate::LoadedMods::new(&mut machine, &mut hosts).expect("paired host");
        crate::drive_loaded(&mut loaded, &environment).expect("optional failure permits startup");
        let supplied = open_resources(&mut loaded).expect("failed owners are skipped");
        assert_eq!(supplied.generated(), []);
        assert_eq!(supplied.bytes(&path("assets/failed.json")), None);
        assert_eq!(host.calls.get(), 0);
    }

    #[test]
    fn a_mod_supplying_another_mods_content_is_refused() {
        let mut mods: Vec<Box<dyn Mod>> = vec![Box::new(
            Supplying::new("thief_mod", &[("assets/taken.json", "t")]).declaring_for("owner_mod"),
        )];
        let mut machine = machine(vec![entry("thief_mod", &[Side::DedicatedServer])]);

        assert_eq!(
            open_resources(
                &mut crate::LoadedMods::new(&mut machine, &mut mods).expect("complete host set")
            ),
            Err(ResourceRefused::ForeignDeclaration {
                mod_id: id("thief_mod"),
                owner: id("owner_mod"),
            })
        );
    }
}
