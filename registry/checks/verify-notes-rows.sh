#!/usr/bin/env bash
# Derives the denominator M6 publishes, from the rows it is a count of.
#
# `evidence/m6/counterpart-summary.json` publishes three numbers per counterpart
# — exercised, declarableOnly and observableAreas — and ROADMAP.md calls the
# third "the honest denominator this milestone's green sits over". Round 1 of the
# M6-W6 review found that the rows those numbers are counted from were kept
# nowhere: 547 classified rows existed only in one session's temporary
# directory, so no later reader could reproduce the denominator or contest a row.
# It also found that the classification was a reader interpreting free prose for
# 307 of the 547 rows, and that every one of the handful of genuinely ambiguous
# rows had been resolved in the direction that shrinks the denominator.
#
# So the rows are the record. Each `| §…` row of each package's section table
# begins with a verdict published in `checks/counterpart-verdicts.tsv`, that
# table says which of three classes the verdict counts as, and this check adds
# them up and holds `records/m6-notes-row-counts.json` to the sum. The producer
# of a count and the record of a count are no longer the same hand: the packages
# are written by twelve hands, the vocabulary is a tracked decision, and the
# arithmetic is here.
#
# Nothing here reads the counterpart's Rust. A row that says "implemented" and is
# not is invisible to this check and is what step 5 of
# `records/counterpart-checklist.md` and the independent review exist to catch.
# This check answers a narrower question: that the number published is the number
# the rows carry.
#
#   checks/verify-notes-rows.sh            derive, compare, and report
#   checks/verify-notes-rows.sh --write    print the derived JSON on stdout
#
# The `--write` form is how records/m6-notes-row-counts.json is produced. It is
# generated by this check and never written by hand, so the record cannot say
# something the rows do not.
set -euo pipefail

checks_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=checks/public-repo.sh
. "$checks_dir/public-repo.sh"

verdicts="$checks_dir/counterpart-verdicts.tsv"
schema="$checks_dir/counterpart-evidence.schema.json"
summary="$repo_root/evidence/m6/counterpart-summary.json"
counts="$registry_root/records/m6-notes-row-counts.json"
mods_dir="$registry_root/mods"

write=0
case "${1:-}" in
  --write) write=1 ;;
  '') ;;
  *)
    printf 'notes row check failed:\n- unknown argument: %s\n' "$1" >&2
    exit 1
    ;;
esac

violations=()
note() { violations+=("$1"); }

# What this check does not reach. Printed on every run, passing or failing, for
# the reason checks/verify-primitives.sh states at length: a gate that says what
# it does not cover is worth more than one that implies it covers everything.
limits=(
  "it counts a row's word, not the package's behaviour: a row that says implemented over a dispatch that resolves a name and does nothing is counted exercised here and is caught by reading or not at all"
  "it reads the table under '## What each section became' and nothing else, so a section marker in another table of the same file is outside this count and is reported beside the verdict rather than silently skipped"
  "the vocabulary is a tracked decision, so a hand that classifies a row wrongly and publishes a verdict that agrees with it passes; what it stops is a row with no verdict at all and a record that disagrees with its rows"
  "it holds the milestone summary's three figures per counterpart to the rows and nothing else in that summary: suites, digests and provenance are bound by the other checks or by the milestone"
)
if [ ${#limits[@]} -lt 3 ]; then
  printf 'notes row check failed:\n- this check states less than it must about what it cannot reach\n' >&2
  exit 1
fi

for path in "$verdicts" "$mods_dir"; do
  if [ ! -e "$path" ]; then
    printf 'notes row check failed:\n- missing input: %s\n' "${path#"$registry_root/"}" >&2
    exit 1
  fi
done

# The vocabulary, read rather than restated. Every class this check knows is
# named here and nowhere else in this file's logic.
declare -A class_of
verdict_count=0
while IFS=$'\t' read -r verdict class rest; do
  case "$verdict" in '' | '#'*) continue ;; esac
  case "$class" in
    exercised | declarable-only | excluded) ;;
    *)
      note "checks/counterpart-verdicts.tsv gives the verdict '$verdict' a class this check does not define: $class"
      continue
      ;;
  esac
  if [ -n "${class_of[$verdict]:-}" ]; then
    note "checks/counterpart-verdicts.tsv publishes the verdict '$verdict' twice, so which class a row carrying it counts as depends on read order"
    continue
  fi
  class_of["$verdict"]="$class"
  verdict_count=$((verdict_count + 1))
done <"$verdicts"

if [ "$verdict_count" -eq 0 ]; then
  printf 'notes row check failed:\n- checks/counterpart-verdicts.tsv publishes no verdict, so every row would be unknown or every row would pass by looking for nothing\n' >&2
  exit 1
fi

mapfile -t packages < <(find "$mods_dir" -mindepth 1 -maxdepth 1 -type d -printf '%P\n' | LC_ALL=C sort)
if [ ${#packages[@]} -eq 0 ]; then
  printf 'notes row check failed:\n- mods/ holds no package, so this check would pass over an empty set\n' >&2
  exit 1
fi

# The verdict table, flattened for awk: one line per verdict, longest first, so
# the first match is the longest match and "declarable only" is never read as a
# cell that merely starts with a word.
verdict_lines=""
for verdict in "${!class_of[@]}"; do
  verdict_lines+="${#verdict}\t$verdict\t${class_of[$verdict]}\n"
done
sorted_verdicts="$(printf "$verdict_lines" | LC_ALL=C sort -t$'\t' -k1,1nr -k2,2 | cut -f2,3)"

rows_total=0
outside_total=0
declare -A carried_verdicts
declare -A ex_of do_of xc_of
json_rows=()

for package in "${packages[@]}"; do
  notes="$mods_dir/$package/NOTES.md"
  id="${package//-/_}"
  if [ ! -f "$notes" ]; then
    note "mods/$package carries no NOTES.md, so it publishes no section table and no rows to count"
    continue
  fi

  # One pass over the file. The section table is the one under the heading named
  # here; a second such heading is a failure rather than a choice this makes.
  parsed="$(
    LC_ALL=C awk -F'\t' -v id="$id" '
      NR == FNR { verdict[++n] = $1; vclass[n] = $2; next }
      /^## / {
        if ($0 == "## What each section became") { heading++; inside = 1 }
        else { inside = 0 }
        next
      }
      /^\|[[:space:]]*§/ {
        if (!inside) { outside++; next }
        if (gsub(/\|/, "|") != 4) {
          printf "!row %d of %s is not three cells: %s\n", FNR, id, $0
          next
        }
        line = $0
        sub(/^\|[[:space:]]*/, "", line)
        sub(/[[:space:]]*\|[[:space:]]*$/, "", line)
        split(line, cell, /[[:space:]]*\|[[:space:]]*/)
        section = cell[1]
        here = cell[2]
        if (here == "") {
          printf "!row %d of %s carries an empty verdict cell\n", FNR, id
          next
        }
        found = ""
        for (i = 1; i <= n; i++) {
          v = verdict[i]
          if (substr(here, 1, length(v)) != v) continue
          tail = substr(here, length(v) + 1, 1)
          if (tail == "" || tail == " " || tail == "," || tail == ";") { found = vclass[i]; carried = v; break }
        }
        if (found == "") {
          printf "!%s row \"%s\" begins with no verdict checks/counterpart-verdicts.tsv publishes: %s\n", id, section, here
          next
        }
        printf "+%s\n", carried
        count[found]++
        rows++
        next
      }
      END {
        if (heading != 1) {
          printf "!%s carries %d headings named \"What each section became\", and this check counts the rows under exactly one\n", id, heading
        }
        if (rows == 0) {
          printf "!%s publishes no section row, so its counts would be a sum over nothing\n", id
        }
        printf "=%d\t%d\t%d\t%d\t%d\n", count["exercised"], count["declarable-only"], count["excluded"], rows, outside
      }
    ' <(printf '%s\n' "$sorted_verdicts") "$notes"
  )"

  while IFS= read -r line; do
    case "$line" in
      '!'*) note "${line#!}" ;;
      '+'*) carried_verdicts["${line#+}"]=1 ;;
      '='*)
        IFS=$'\t' read -r ex dcl xcl rows outside <<<"${line#=}"
        ex_of["$id"]="$ex"
        do_of["$id"]="$dcl"
        xc_of["$id"]="$xcl"
        rows_total=$((rows_total + rows))
        outside_total=$((outside_total + outside))
        ;;
    esac
  done <<<"$parsed"
done

# A published verdict no row carries is a permission granted ahead of the work it
# would excuse. Rule L3 of checks/verify-counterparts.sh refuses a padded lexicon
# for the same reason and this table is refused on the same terms, so the
# vocabulary tracks the tables rather than running ahead of them.
for verdict in "${!class_of[@]}"; do
  if [ -z "${carried_verdicts[$verdict]:-}" ]; then
    note "checks/counterpart-verdicts.tsv publishes the verdict '$verdict' and no row of any section table carries it, so the vocabulary is wider than the tables it governs"
  fi
done

# The JSON this check is the only producer of.
for package in "${packages[@]}"; do
  id="${package//-/_}"
  [ -n "${ex_of[$id]:-}" ] || continue
  json_rows+=("$(printf '  "%s": { "exercised": %d, "declarableOnly": %d, "excluded": %d, "observableAreas": %d }' \
    "$id" "${ex_of[$id]}" "${do_of[$id]}" "${xc_of[$id]}" "$((ex_of[$id] + do_of[$id]))")")
done

if [ "$write" -eq 1 ]; then
  if [ ${#violations[@]} -ne 0 ]; then
    printf 'notes row check failed, so it writes nothing:\n' >&2
    printf -- '- %s\n' "${violations[@]}" >&2
    exit 1
  fi
  printf '{\n'
  printf '%s,\n' "${json_rows[@]::${#json_rows[@]}-1}"
  printf '%s\n' "${json_rows[-1]}"
  printf '}\n'
  exit 0
fi

if [ ! -f "$counts" ]; then
  note "records/m6-notes-row-counts.json is not there, so the rows are counted here and compared against nothing"
else
  mapfile -t recorded < <(jq -r 'to_entries[] | "\(.key)\t\(.value.exercised)\t\(.value.declarableOnly)\t\(.value.excluded)\t\(.value.observableAreas)"' "$counts" | LC_ALL=C sort)
  declare -A seen
  for entry in ${recorded[@]+"${recorded[@]}"}; do
    IFS=$'\t' read -r id r_ex r_do r_xc r_oa <<<"$entry"
    seen["$id"]=1
    if [ -z "${ex_of[$id]:-}" ]; then
      note "records/m6-notes-row-counts.json counts $id and mods/ carries no package whose rows were counted here"
      continue
    fi
    derived_oa=$((ex_of[$id] + do_of[$id]))
    if [ "$r_ex" != "${ex_of[$id]}" ] || [ "$r_do" != "${do_of[$id]}" ] || [ "$r_xc" != "${xc_of[$id]}" ] || [ "$r_oa" != "$derived_oa" ]; then
      note "records/m6-notes-row-counts.json records $id as exercised $r_ex, declarable-only $r_do, excluded $r_xc, observableAreas $r_oa, and its rows carry exercised ${ex_of[$id]}, declarable-only ${do_of[$id]}, excluded ${xc_of[$id]}, observableAreas $derived_oa"
    fi
  done
  for package in "${packages[@]}"; do
    id="${package//-/_}"
    [ -n "${ex_of[$id]:-}" ] || continue
    if [ -z "${seen[$id]:-}" ]; then
      note "mods/$package publishes rows and records/m6-notes-row-counts.json counts no $id, so a package's denominator is recorded nowhere"
    fi
  done
fi

# The evidence row schema, run rather than written.
#
# checks/counterpart-evidence.schema.json is one of the three artefacts M6-W5
# exists to produce, and until round 1 of the M6-W6 review it rejected every row
# of the record its own description names: id and entry were the other way round,
# and its route enum held the wave manifest's method strings rather than the two
# the record uses. It had been left out of the gate, and an artefact nothing runs
# is an artefact nothing corrects. It runs here over the evidence rows, whose
# counterpart set and counts must also match today's classified notes.
if [ ! -f "$schema" ]; then
  note "checks/counterpart-evidence.schema.json is not there, so the public summary's rows are validated against nothing"
elif [ ! -f "$summary" ]; then
  note "the repository does not carry evidence/m6/counterpart-summary.json, which is the record checks/counterpart-evidence.schema.json describes"
elif ! command -v check-jsonschema >/dev/null 2>&1; then
  note "check-jsonschema is not on PATH, and a schema that does not run is a schema nothing corrects"
else
  rows_dir="$(mktemp -d)"
  row_count="$(jq '.counterparts | length' "$summary")"
  if [ "$row_count" -lt 1 ]; then
    note "evidence/m6/counterpart-summary.json carries no counterpart row, so the schema would pass over an empty set"
  else
    jq -c '.counterparts[]' "$summary" | {
      index=0
      while IFS= read -r row; do
        index=$((index + 1))
        printf '%s\n' "$row" >"$rows_dir/row-$index.json"
      done
    }
    if ! schema_out="$(check-jsonschema --schemafile "$schema" "$rows_dir"/row-*.json 2>&1)"; then
      note "checks/counterpart-evidence.schema.json rejects a row of the record it describes: $(printf '%s' "$schema_out" | tr '\n' ' ')"
    else
      schema_rows="$row_count"
    fi
  fi
  rm -rf "$rows_dir"
  while IFS=$'\t' read -r id s_ex s_do s_oa; do
    if [ -z "${ex_of[$id]:-}" ]; then
      note "evidence/m6/counterpart-summary.json publishes $id and no package under mods/ carries rows for it"
    elif [ "$s_ex" != "${ex_of[$id]}" ] || [ "$s_do" != "${do_of[$id]}" ] || [ "$s_oa" != "$((ex_of[$id] + do_of[$id]))" ]; then
      note "evidence/m6/counterpart-summary.json publishes $id as exercised $s_ex, declarable-only $s_do, observableAreas $s_oa, and its rows carry exercised ${ex_of[$id]}, declarable-only ${do_of[$id]}, observableAreas $((ex_of[$id] + do_of[$id]))"
    fi
  done < <(jq -r '.counterparts[] | "\(.id)\t\(.exercised)\t\(.declarableOnly)\t\(.observableAreas)"' "$summary")
  for package in "${packages[@]}"; do
    id="${package//-/_}"
    [ -n "${ex_of[$id]:-}" ] || continue
    jq -e --arg id "$id" '.counterparts | any(.id == $id)' "$summary" >/dev/null || note "mods/$package publishes rows and evidence/m6/counterpart-summary.json carries no row for $id"
  done
fi

if [ ${#violations[@]} -ne 0 ]; then
  printf 'notes row check failed:\n' >&2
  printf -- '- %s\n' "${violations[@]}" >&2
  printf 'and what this check cannot reach, which is unchanged by the failures above:\n' >&2
  printf -- '- %s\n' "${limits[@]}" >&2
  exit 1
fi

sum_ex=0
sum_do=0
sum_xc=0
for package in "${packages[@]}"; do
  id="${package//-/_}"
  [ -n "${ex_of[$id]:-}" ] || continue
  sum_ex=$((sum_ex + ex_of[$id]))
  sum_do=$((sum_do + do_of[$id]))
  sum_xc=$((sum_xc + xc_of[$id]))
done

printf 'notes rows derived: %s section rows over %s packages, each carrying one of %s published verdicts; %s exercised, %s declarable-only, %s excluded, denominator %s, and records/m6-notes-row-counts.json and the milestone summary both agree row for row; section markers outside a section table, counted by nothing here: %s; %s evidence rows validated against checks/counterpart-evidence.schema.json\n' \
  "$rows_total" "${#packages[@]}" "$verdict_count" "$sum_ex" "$sum_do" "$sum_xc" "$((sum_ex + sum_do))" "$outside_total" "${schema_rows:-0}"
printf 'and what this check cannot reach:\n'
printf -- '- %s\n' "${limits[@]}"
