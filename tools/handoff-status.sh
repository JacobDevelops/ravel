#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
python3 - <<'PY'
import html
import json
import pathlib
import re
import subprocess


def run(*args):
    try:
        result = subprocess.run(args, capture_output=True, text=True, timeout=30, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def cell(text):
    return html.escape(str(text), quote=False).replace("|", "&#124;").replace("\n", "; ")


begin = "<!-- handoff-status:begin -->"
end = "<!-- handoff-status:end -->"
path = pathlib.Path("docs/handoff/HANDOFF.md")
text = path.read_text()
if text.count(begin) != 1 or text.count(end) != 1 or text.index(begin) >= text.index(end):
    raise SystemExit("HANDOFF.md must contain exactly one ordered handoff-status marker pair")
rows = []
for line in pathlib.Path("ROADMAP.md").read_text().splitlines():
    if re.match(r"\| WP\d+ —", line):
        columns = [column.strip() for column in line.strip("|").split("|")]
        if len(columns) != 4:
            raise SystemExit("unexpected ROADMAP work-package row")
        rows.append((columns[0], columns[3]))
if not rows:
    raise SystemExit("ROADMAP.md has no forward work-package rows")
quality_rows = re.findall(r"^\| Code quality[^|]*\|.*\|$", text, re.MULTILINE)
quality_row = quality_rows[0] if len(quality_rows) == 1 else None
raw = run("numen", "refine", "status", "--json")
try:
    status = json.loads(raw) if raw is not None else None
except json.JSONDecodeError:
    status = None
if isinstance(status, dict) and status.get("scores"):
    quality = "Scores: " + json.dumps(status["scores"], sort_keys=True)
    quality += "; open findings: " + str(status.get("open", "unknown"))
    quality += "; freshness: " + str(status.get("context", {}).get("freshness", "unknown"))
    quality_row = f"| Code quality (last recorded) | {cell(quality)} |"
elif quality_row is None:
    raise SystemExit("refinement status unavailable and no existing quality row to preserve")
recent = run("jj", "log", "-r", "ancestors(@, 6) ~ @", "--no-graph", "-T",
             'change_id.short() ++ " " ++ description.first_line() ++ "\\n"')
block = "\n\nGenerated by `bash tools/handoff-status.sh`; roadmap status is not a fresh gate result.\n\n"
block += "| Area | State |\n| --- | --- |\n"
block += "".join(f"| {cell(area)} | {cell(state)} |\n" for area, state in rows)
block += quality_row + "\n\n"
updated = text[:text.index(begin) + len(begin)] + block + text[text.index(end):]
path.write_text(updated)
print(block.strip())
print("\nRecent changes (checkout ancestry; stdout only):")
print(recent or "Unavailable: jj log failed or ancestry is empty")
PY
